"""Generates install_ps09.sh (a self-extracting copy of the code for a machine without git) from the canonical files.

The installer is never edited by hand: run this after changing any packaged file. `--check` fails (exit 1) if the
embedded copies differ from the files in the repository, so stale content cannot go unnoticed (run_all.ps1 checks it).
Text files are packed with LF line endings, whatever the Windows checkout uses.

Usage: python scripts/build_installer.py [--check]
"""
import argparse, base64, gzip, io, sys, tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "install_ps09.sh"
FILES = ["team.py", "validate.py", "profile_run.py", "run_ablation.py", "run_all.sh", "run_all.ps1", "README.md",
         "TRACKER.md", "requirements.txt", "requirements-gpu.txt", "demo.py"]
DIRS = ["scripts", "tests"]

HEADER = """#!/usr/bin/env bash
# PS-09 installer (GENERATED by scripts/build_installer.py -- do not edit by hand).
# Creates ~/Desktop/ps09 (or the folder given as $1) with all code files, then runs the GPU workflow.
# Usage:  bash install_ps09.sh            -> installs into ~/Desktop/ps09 and starts run_all.sh
#         bash install_ps09.sh DIR --no-run
# Preferred alternative when the machine has git:  git clone / git pull  (then: bash run_all.sh)
set -e
DEST="${1:-$HOME/Desktop/ps09}"
mkdir -p "$DEST"
sed -n '/^__ARCHIVE__$/,$p' "$0" | tail -n +2 | base64 -d | tar xz -C "$DEST"
echo "Installed into $DEST:"; ls "$DEST"
if [ "${2:-}" != "--no-run" ]; then cd "$DEST" && bash run_all.sh 2>&1 | tee results_log.txt; fi
exit 0
__ARCHIVE__
"""


def packaged():
    files = [ROOT / f for f in FILES if (ROOT / f).exists()]
    for d in DIRS:
        files += sorted(p for p in (ROOT / d).rglob("*") if p.is_file() and p.suffix in (".py", ".sh", ".md", ".txt")
                        and "__pycache__" not in p.parts)
    return {p.relative_to(ROOT).as_posix(): p.read_bytes().replace(b"\r\n", b"\n") for p in files}


def build(contents):
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as gz:  # deterministic bytes
        with tarfile.open(fileobj=gz, mode="w") as tar:
            for name, data in sorted(contents.items()):
                ti = tarfile.TarInfo(name)
                ti.size, ti.mtime, ti.mode = len(data), 0, 0o755 if name.endswith(".sh") else 0o644
                tar.addfile(ti, io.BytesIO(data))
    b64 = base64.encodebytes(buf.getvalue()).decode()
    return (HEADER + b64).encode()


def embedded(path):
    raw = path.read_bytes().replace(b"\r\n", b"\n")
    i = raw.index(b"\n__ARCHIVE__\n") + len(b"\n__ARCHIVE__\n")
    data = base64.decodebytes(raw[i:])
    out = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for m in tar.getmembers():
            if m.isfile():
                out[m.name] = tar.extractfile(m).read().replace(b"\r\n", b"\n")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = packaged()
    if a.check:
        if not OUT.exists():
            print("install_ps09.sh missing"); sys.exit(1)
        have = embedded(OUT)
        stale = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if stale:
            print("install_ps09.sh is STALE for:", ", ".join(stale), "\n-> run: python scripts/build_installer.py")
            sys.exit(1)
        print(f"install_ps09.sh is in sync ({len(want)} files)")
        return
    OUT.write_bytes(build(want))
    print(f"wrote {OUT.name}: {len(want)} files, {OUT.stat().st_size // 1024} KiB")


if __name__ == "__main__":
    main()
